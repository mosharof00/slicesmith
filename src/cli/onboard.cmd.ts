import path from 'node:path';
import chalk from 'chalk';
import { Logger } from '../utils/logger.js';
import { ConfigManager } from '../core/config.js';
import { CodebaseScanner } from '../core/scanner.js';
import { StackPackRegistry } from '../packs/registry.js';
import { writeTextSafe } from '../utils/files.js';

export async function onboardCommand(): Promise<void> {
  Logger.header('SliceSmith Onboarding: Scanning Boilerplates & Codebases');

  const config = ConfigManager.load();
  const hubDir = path.dirname(ConfigManager.findConfigFile()!);
  const summaryLines: string[] = [];

  let briefContent = `# 📖 Project Brief: ${config.name}\n\n`;
  briefContent += `> Generated by SliceSmith Onboarding on ${new Date().toISOString().split('T')[0]}.\n\n`;
  briefContent += `## Repositories & Tech Stacks\n\n`;

  for (const repo of config.repos) {
    const absPath = path.resolve(hubDir, repo.path);
    Logger.info(`Scanning [${repo.role}] ${repo.id} at ${repo.path}...`);

    try {
      const scanResult = CodebaseScanner.scan(absPath);
      CodebaseScanner.saveRegistry(hubDir, repo.id, scanResult);

      const stackPack = StackPackRegistry.get(scanResult.detectedStack);

      briefContent += `### ${repo.id.toUpperCase()} (${repo.role})\n`;
      briefContent += `- **Stack**: ${scanResult.detectedStack.toUpperCase()} ${stackPack ? `(StackPack: v${stackPack.version})` : ''}\n`;
      briefContent += `- **Path**: \`${repo.path}\`\n`;
      briefContent += `- **Modules detected**: ${scanResult.modules.length > 0 ? scanResult.modules.join(', ') : 'None'}\n`;
      if (scanResult.templateLeftovers.length > 0) {
        briefContent += `- **⚠️ Template Leftovers (Ignored by Agents)**: ${scanResult.templateLeftovers.join(', ')}\n`;
      }
      briefContent += `\n`;

      summaryLines.push(
        `[${repo.role}] ${repo.id}: ${scanResult.detectedStack} (${scanResult.modules.length} modules, ${scanResult.templateLeftovers.length} leftovers)`
      );
    } catch (err: any) {
      Logger.warn(`Could not scan ${repo.id}: ${err.message}`);
      summaryLines.push(`[${repo.role}] ${repo.id}: Failed to scan`);
    }
  }

  // Write docs/PROJECT_BRIEF.md
  const briefPath = path.join(hubDir, 'docs', 'PROJECT_BRIEF.md');
  writeTextSafe(briefPath, briefContent);
  Logger.success(`Saved project overview to docs/PROJECT_BRIEF.md`);

  Logger.box('Onboarding Complete!', [
    ...summaryLines,
    'Boilerplate registry saved: .slicesmith/boilerplate-registry.json',
    'Next step: Run \'slicesmith plan\' to structure vertical slices & tasks',
  ]);
}

